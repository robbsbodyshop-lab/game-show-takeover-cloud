/** Packs the sprites into one sheet and renders it as an SVG of `<symbol>`s placed with `<use>`. */
import type { Pixel, SpriteArt } from './pixelGrid.ts';

export interface Placement {
  id: string;
  x: number;
  y: number;
  w: number;
  h: number;
}

export interface PackedSheet {
  width: number;
  height: number;
  placements: Placement[];
}

export const SHEET_WIDTH = 320;

/** Shelf packing: tallest sprites first (stable), left to right, wrapping at the sheet width. */
export const packSprites = (art: readonly SpriteArt[], sheetWidth = SHEET_WIDTH): PackedSheet => {
  const order = art
    .map((sprite, index) => ({ sprite, index }))
    .sort((a, b) => b.sprite.height - a.sprite.height || a.index - b.index);
  const placements: Placement[] = [];
  let x = 0;
  let y = 0;
  let rowHeight = 0;
  for (const { sprite } of order) {
    if (x + sprite.width > sheetWidth) {
      x = 0;
      y += rowHeight;
      rowHeight = 0;
    }
    placements.push({ id: sprite.id, x, y, w: sprite.width, h: sprite.height });
    x += sprite.width;
    rowHeight = Math.max(rowHeight, sprite.height);
  }
  return { width: sheetWidth, height: y + rowHeight, placements };
};

/** One path per colour; identical horizontal runs in consecutive rows merge into one rectangle. */
const symbolPaths = (sprite: SpriteArt): string => {
  const byColour = new Map<string, string[]>();
  const open = new Map<string, { x: number; len: number; y: number; colour: string }>();
  const emit = (colour: string, x: number, y: number, w: number, h: number): void => {
    const list = byColour.get(colour) ?? [];
    list.push(`M${x.toString()} ${y.toString()}h${w.toString()}v${h.toString()}h-${w.toString()}z`);
    byColour.set(colour, list);
  };
  const rowRuns = (y: number): { x: number; len: number; colour: string }[] => {
    const runs: { x: number; len: number; colour: string }[] = [];
    let x = 0;
    while (x < sprite.width) {
      const colour: Pixel = sprite.pixels[y * sprite.width + x] ?? null;
      if (colour === null) {
        x += 1;
        continue;
      }
      let len = 1;
      while (x + len < sprite.width && (sprite.pixels[y * sprite.width + x + len] ?? null) === colour)
        len += 1;
      runs.push({ x, len, colour });
      x += len;
    }
    return runs;
  };
  for (let y = 0; y <= sprite.height; y++) {
    const runs = y < sprite.height ? rowRuns(y) : [];
    const keys = new Set(runs.map((r) => `${r.colour}:${r.x.toString()}:${r.len.toString()}`));
    for (const [key, run] of [...open]) {
      if (!keys.has(key)) {
        emit(run.colour, run.x, run.y, run.len, y - run.y);
        open.delete(key);
      }
    }
    for (const r of runs) {
      const key = `${r.colour}:${r.x.toString()}:${r.len.toString()}`;
      if (!open.has(key)) open.set(key, { x: r.x, len: r.len, y, colour: r.colour });
    }
  }
  return [...byColour.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([colour, parts]) => `<path fill="${colour}" d="${parts.join('')}"/>`)
    .join('');
};

export const renderSheetSvg = (art: readonly SpriteArt[], sheet: PackedSheet): string => {
  const byId = new Map(art.map((sprite) => [sprite.id, sprite]));
  const lines: string[] = [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<!-- Generated by src/games/puzzle/tools/buildSprites.ts. Original pixel art; do not edit by hand. -->',
    `<svg xmlns="http://www.w3.org/2000/svg" width="${sheet.width.toString()}" height="${sheet.height.toString()}" viewBox="0 0 ${sheet.width.toString()} ${sheet.height.toString()}" shape-rendering="crispEdges">`,
    '<defs>',
  ];
  for (const p of sheet.placements) {
    const sprite = byId.get(p.id);
    if (!sprite) continue;
    lines.push(
      `<symbol id="${p.id}" viewBox="0 0 ${p.w.toString()} ${p.h.toString()}">${symbolPaths(sprite)}</symbol>`,
    );
  }
  lines.push('</defs>');
  for (const p of sheet.placements) {
    lines.push(
      `<use href="#${p.id}" x="${p.x.toString()}" y="${p.y.toString()}" width="${p.w.toString()}" height="${p.h.toString()}"/>`,
    );
  }
  lines.push('</svg>', '');
  return lines.join('\n');
};

/** The source of `sprites.ts`: id to rect, in sheet pixels (1x). */
export const renderSpritesModule = (sheet: PackedSheet): string => {
  const rows = [...sheet.placements]
    .sort((a, b) => a.id.localeCompare(b.id))
    .map(
      (p) =>
        `  '${p.id}': { x: ${p.x.toString()}, y: ${p.y.toString()}, w: ${p.w.toString()}, h: ${p.h.toString()} },`,
    );
  return [
    '// Generated by src/games/puzzle/tools/buildSprites.ts from the art in ./art. Do not edit by hand.',
    '',
    'export interface SpriteRect {',
    '  x: number;',
    '  y: number;',
    '  w: number;',
    '  h: number;',
    '}',
    '',
    `export const SHEET_WIDTH = ${sheet.width.toString()};`,
    `export const SHEET_HEIGHT = ${sheet.height.toString()};`,
    '',
    '/** Source rectangle of every sprite in `public/puzzle/sprites.svg`, in 1x sheet pixels. */',
    'export const SPRITES = {',
    ...rows,
    '} as const satisfies Record<string, SpriteRect>;',
    '',
    'export type SpriteId = keyof typeof SPRITES;',
    '',
    'export const SPRITE_SHEET_URL = `${import.meta.env.BASE_URL}puzzle/sprites.svg`;',
    '',
  ].join('\n');
};
